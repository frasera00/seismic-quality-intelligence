"""Plot calibrated Isolation Forest QC predictions over one validation gather."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np
import yaml
from joblib import load
from sklearn.model_selection import GroupShuffleSplit

from seismic_quality_intelligence.gather_features import (
    flatten_gather_dataset,
)
from seismic_quality_intelligence.synthetic_gather import (
    generate_gather_dataset,
)


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description=(
            "Plot one validation seismic gather with known anomalies, "
            "high-confidence anomaly alerts, and manual-review traces."
        )
    )

    parser.add_argument(
        "--config",
        type=Path,
        default=Path("configs/baseline.yaml"),
        help="Path to the YAML experiment configuration.",
    )
    parser.add_argument(
        "--model-path",
        type=Path,
        default=Path("reports/gather_qc_model.joblib"),
        help="Path to the trained Isolation Forest pipeline.",
    )
    parser.add_argument(
        "--policy-path",
        type=Path,
        default=Path("reports/operating_policy.yaml"),
        help="Path to the threshold policy generated by calibration.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("reports/figures"),
        help="Directory for generated figures.",
    )
    parser.add_argument(
        "--gather-index",
        type=int,
        default=None,
        help=(
            "Original validation-gather index to plot. "
            "If omitted, select a random validation gather."
        ),
    )

    return parser.parse_args()


def load_yaml(path: Path) -> dict[str, Any]:
    """Load a YAML file into a Python dictionary."""
    if not path.exists():
        raise FileNotFoundError(f"Required file does not exist: {path}")

    with path.open(encoding="utf-8") as file:
        content = yaml.safe_load(file)

    if not isinstance(content, dict):
        raise ValueError(f"Expected a YAML mapping in: {path}")

    return content


def load_operating_policy(path: Path) -> dict[str, Any]:
    """Load and validate the learned QC operating policy."""
    policy = load_yaml(path)

    required_keys = {
        "policy_name",
        "threshold",
        "review_threshold",
        "decision_rule",
        "review_rule",
    }

    missing_keys = required_keys.difference(policy)

    if missing_keys:
        missing = ", ".join(sorted(missing_keys))
        raise ValueError(f"Operating policy is missing required keys: {missing}")

    threshold = float(policy["threshold"])
    review_threshold = float(policy["review_threshold"])

    if threshold >= review_threshold:
        raise ValueError(
            "Operating policy requires threshold < review_threshold. "
            "The alert threshold must be more negative than the "
            "manual-review threshold."
        )

    policy["threshold"] = threshold
    policy["review_threshold"] = review_threshold

    return policy


def classify_outcomes(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> np.ndarray:
    """Classify each trace as TN, TP, FP, or FN."""
    y_true = np.asarray(y_true, dtype=np.int32)
    y_pred = np.asarray(y_pred, dtype=np.int32)

    outcomes = np.full(y_true.shape, "", dtype="<U2")

    outcomes[(y_true == 0) & (y_pred == 0)] = "TN"
    outcomes[(y_true == 1) & (y_pred == 1)] = "TP"
    outcomes[(y_true == 0) & (y_pred == 1)] = "FP"
    outcomes[(y_true == 1) & (y_pred == 0)] = "FN"

    return outcomes


def classify_qc_status(
    scores: np.ndarray,
    alert_threshold: float,
    review_threshold: float,
) -> np.ndarray:
    """Classify scores as alert, review, or no-alert."""
    scores = np.asarray(scores, dtype=float)

    status = np.full(scores.shape, "normal", dtype="<U8")

    status[scores < alert_threshold] = "alert"

    review_mask = (scores >= alert_threshold) & (scores < review_threshold)
    status[review_mask] = "review"

    return status


def select_validation_gather(
    groups_val: np.ndarray,
    requested_gather: int | None,
) -> int:
    """Return a requested validation gather or a random validation gather."""
    available_gathers = np.unique(groups_val)

    if requested_gather is not None:
        if requested_gather not in available_gathers:
            examples = ", ".join(str(value) for value in available_gathers[:10])
            raise ValueError(
                f"Gather {requested_gather} is not in validation. "
                f"Example available IDs: {examples}"
            )

        return int(requested_gather)

    rng = np.random.default_rng()

    return int(rng.choice(available_gathers))


def add_trace_marker(
    axis: plt.Axes,
    offset: float,
    outcome: str,
) -> None:
    """Add a color-coded vertical line for a classification outcome."""
    colors = {
        "TP": "xkcd:aqua green",
        "FP": "xkcd:black",
        "FN": "xkcd:magenta",
    }

    if outcome == "TN":
        return

    axis.axvline(
        offset,
        color=colors[outcome],
        linewidth=2,
        linestyle="--",
        alpha=1,
        zorder=4,
    )


def add_anomaly_label(
    axis: plt.Axes,
    offset: float,
    anomaly_type: str,
    outcome: str,
    time: np.ndarray,
) -> None:
    """Label known anomalous traces near the bottom of the gather."""
    if outcome not in {"TP", "FN"}:
        return

    color = "xkcd:aqua green" if outcome == "TP" else "xkcd:magenta"

    axis.text(
        offset,
        float(time.max() - 0.5),
        anomaly_type,
        rotation=90,
        fontsize=12,
        color="white",
        ha="center",
        va="top",
        clip_on=True,
        zorder=5,
        bbox={
            "facecolor": color,
            "edgecolor": "none",
            "alpha": 0.85,
            "pad": 1.5,
        },
    )


def main() -> None:
    """Recreate validation data and plot a calibrated QC decision."""
    args = parse_args()

    config = load_yaml(args.config)
    policy = load_operating_policy(args.policy_path)

    data_cfg = config["data"]
    split_cfg = config["split"]

    alert_threshold = float(policy["threshold"])
    review_threshold = float(policy["review_threshold"])
    policy_name = str(policy["policy_name"])

    dataset = generate_gather_dataset(
        n_gathers=data_cfg["n_gathers"],
        n_traces=data_cfg["n_traces"],
        anomaly_fraction=data_cfg["anomaly_fraction"],
        duration=data_cfg["duration"],
        dt=data_cfg["dt"],
        max_offset=data_cfg["max_offset"],
        f0=data_cfg["f0"],
        noise_std=data_cfg["noise_std"],
        seed=data_cfg["seed"],
    )

    gathers = np.asarray(dataset["gathers"])
    labels = np.asarray(dataset["labels"], dtype=np.int32)
    anomaly_types = np.asarray(
        dataset["anomaly_type"],
        dtype=str,
    )
    offsets = np.asarray(dataset["offsets"], dtype=float)
    time = np.asarray(dataset["time"], dtype=float)

    X, y, groups = flatten_gather_dataset(
        gathers=gathers,
        labels=labels,
        dt=data_cfg["dt"],
    )

    outer_splitter = GroupShuffleSplit(
        n_splits=1,
        test_size=split_cfg["validation_fraction"],
        random_state=split_cfg["random_state"],
    )

    _, val_idx = next(
        outer_splitter.split(
            X,
            y,
            groups=groups,
        )
    )

    model = load(args.model_path)

    X_val = X[val_idx]
    y_val = y[val_idx]
    groups_val = groups[val_idx]

    scores_val = model.decision_function(X_val)

    y_pred_val = (scores_val < alert_threshold).astype(np.int32)

    gather_id = select_validation_gather(
        groups_val=groups_val,
        requested_gather=args.gather_index,
    )

    local_mask = groups_val == gather_id

    y_true_gather = y_val[local_mask]
    y_pred_gather = y_pred_val[local_mask]
    scores_gather = scores_val[local_mask]

    outcomes = classify_outcomes(
        y_true=y_true_gather,
        y_pred=y_pred_gather,
    )

    qc_status = classify_qc_status(
        scores=scores_gather,
        alert_threshold=alert_threshold,
        review_threshold=review_threshold,
    )

    gather = gathers[gather_id]
    types_gather = anomaly_types[gather_id]

    if gather.shape[0] != offsets.size:
        raise ValueError("Gather trace count does not match the number of offsets.")

    amplitude_scale = float(
        np.percentile(
            np.abs(gather),
            99.0,
        )
    )

    fig, (ax_image, ax_scores) = plt.subplots(
        nrows=2,
        ncols=1,
        figsize=(15, 10),
        height_ratios=[3.0, 1.25],
        sharex=True,
    )

    ax_image.imshow(
        gather.T,
        cmap="seismic",
        aspect="auto",
        vmin=-amplitude_scale,
        vmax=amplitude_scale,
        extent=[
            float(offsets.min()),
            float(offsets.max()),
            float(time.max()),
            float(time.min()),
        ],
    )

    for trace_index, offset in enumerate(offsets):
        add_trace_marker(
            axis=ax_image,
            offset=float(offset),
            outcome=str(outcomes[trace_index]),
        )

        add_anomaly_label(
            axis=ax_image,
            offset=float(offset),
            anomaly_type=str(types_gather[trace_index]),
            outcome=str(outcomes[trace_index]),
            time=time,
        )

    ax_image.plot(
        [],
        [],
        color="xkcd:aqua green",
        linewidth=2,
        linestyle="--",
        label="True positive: high-confidence alert",
    )
    ax_image.plot(
        [],
        [],
        color="xkcd:black",
        linewidth=2,
        linestyle="--",
        label="False positive: high-confidence alert",
    )
    ax_image.plot(
        [],
        [],
        color="xkcd:magenta",
        linewidth=2,
        linestyle="--",
        label="False negative: not auto-alerted",
    )

    ax_image.legend(
        loc="upper right",
        frameon=True,
        fontsize=12,
    )

    ax_image.set_ylabel("Two-way time (s)")
    ax_image.set_title(
        f"Validation gather {gather_id}: calibrated QC predictions\n"
        f"Policy = {policy_name}; "
        f"alert if score < {alert_threshold:.3f}; "
        f"review if score < {review_threshold:.3f}",
        fontsize=12,
    )

    ax_scores.axhline(
        alert_threshold,
        color="black",
        linestyle="--",
        linewidth=1.2,
        label=f"Alert threshold ({alert_threshold:.3f})",
        zorder=2,
    )

    ax_scores.axhline(
        review_threshold,
        color="gray",
        linestyle=":",
        linewidth=1.2,
        label="",
        zorder=2,
    )

    ax_scores.axhspan(
        alert_threshold,
        review_threshold,
        color="gold",
        alpha=0.12,
        label="Threshold calibration shift",
        zorder=0,
    )

    outcome_colors = {
        "TN": "steelblue",
        "TP": "xkcd:aqua green",
        "FP": "xkcd:black",
        "FN": "xkcd:magenta",
    }

    for outcome in ["TN", "TP", "FP", "FN"]:
        outcome_mask = outcomes == outcome

        ax_scores.scatter(
            offsets[outcome_mask],
            scores_gather[outcome_mask],
            color=outcome_colors[outcome],
            s=30,
            label=outcome,
            zorder=3,
        )

    review_mask = qc_status == "review"

    ax_scores.scatter(
        offsets[review_mask],
        scores_gather[review_mask],
        facecolors="none",
        edgecolors="goldenrod",
        linewidths=1.2,
        s=75,
        marker="o",
        label="",
        zorder=4,
    )

    ax_scores.set_xlabel("Offset (m)")
    ax_scores.set_ylabel("IF score")
    ax_scores.set_title(
        "Trace-level Isolation Forest decision scores",
        fontsize=12,
    )
    ax_scores.grid(
        alpha=0.25,
        linewidth=0.5,
    )
    ax_scores.legend(
        ncol=3,
        fontsize=12,
        loc="upper center",
    )

    fig.tight_layout()

    args.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path = args.output_dir / "gather_prediction_overlay.png"

    fig.savefig(
        output_path,
        dpi=300,
        bbox_inches="tight",
    )
    plt.close(fig)

    print(f"Saved figure: {output_path}")
    print(f"Plotted validation gather: {gather_id}")
    print(f"Operating policy: {policy_name}")
    print(f"Alert threshold: {alert_threshold:.6f}")
    print(f"Review threshold: {review_threshold:.6f}")
    print(
        "Outcome counts: "
        f"TN={int(np.sum(outcomes == 'TN'))}, "
        f"TP={int(np.sum(outcomes == 'TP'))}, "
        f"FP={int(np.sum(outcomes == 'FP'))}, "
        f"FN={int(np.sum(outcomes == 'FN'))}"
    )
    print(
        "QC status counts: "
        f"alert={int(np.sum(qc_status == 'alert'))}, "
        f"review={int(np.sum(qc_status == 'review'))}, "
        f"normal={int(np.sum(qc_status == 'normal'))}"
    )


def spike_time(trace: np.ndarray, time: np.ndarray) -> float:
    """Return the time coordinate of the largest absolute-amplitude sample."""
    sample_index = int(np.argmax(np.abs(trace)))
    return float(time[sample_index])


if __name__ == "__main__":
    main()
